   SEED DE LOTES DEMO  ->  LTPD03 (SAE80EMPRE03.FDB)
   ---------------------------------------------------------------------------
   Puebla LTPD03 con 30 lotes de prueba repartidos en los 3 estados del
   Semaforo: 10 criticos, 10 prioritarios y 10 estables, sobre 30 productos
   reales del catalogo INVE03 y 20 lineas distintas (para que los iconos y los
   chips de categoria se vean variados en Entregables / No aptos).

   Las fechas son RELATIVAS a CURRENT_DATE, asi que el script es re-ejecutable:
   corriendolo de nuevo el dia del demo, los lotes se recolocan solos en su
   estado correcto. Es idempotente (borra su propio rango antes de insertar).

   Bandas que aplica LtpdService:
     critico     -> caduca en <= 2 dias (o ya caduco)
     prioritario -> caduca en 3..5 dias
     estable     -> caduca en >= 6 dias

   Los offsets estan elegidos con holgura: los criticos usan <= +2 (nunca se
   "curan" con el paso del tiempo) y los prioritarios usan +4/+5 (siguen siendo
   prioritarios aunque el demo se recorra 1-2 dias).

   CORRER (PowerShell, desde la raiz del repo). Las rutas de abajo son las de
   una instalacion local default de Firebird 2.5 + Aspel SAE 8.00 con la
   Empresa03 ya copiada; ajustalas si tu instalacion vive en otro lado:

     & "C:\Program Files (x86)\Firebird\Firebird_2_5\bin\isql.exe" -user sysdba -password masterkey -i "$PWD\scripts\seed-demo-lotes.sql" "C:\Program Files (x86)\Common Files\Aspel\Sistemas Aspel\SAE8.00\Empresa03\Datos\SAE80EMPRE03.FDB"

   LIMPIAR (deja la DB como estaba):
     DELETE FROM LTPD03 WHERE REG_LTPD BETWEEN 1001 AND 1099;

   NOTA: usa REG_LTPD 1001..1030 (rango propio) para no chocar con el contador
   de Aspel (TBLCONTROL tabla 48) ni con las 6 filas originales (REG_LTPD 1..6),
   que NO se tocan.
--------------------------------------------------------------------------- */

